interface TrailLogoProps {
  slug: string;
  // Icone do grupo, usado quando o slug nao tem logo no mapa.
  fallback: LucideIcon;
  // So tamanho: a cor vem da paleta da trilha.
  className: string;
}

export default function TrailLogo({
  slug,
  fallback: Fallback,
  className,
}: TrailLogoProps) {
  const tinta = trailPaletteOf(slug).text;
  const logo = Object.prototype.hasOwnProperty.call(TRAIL_LOGOS, slug)
    ? TRAIL_LOGOS[slug]
    : null;
  if (!logo) {
    return <Fallback aria-hidden="true" className={`${className} ${tinta}`} />;
  }
  return (
    <svg
      viewBox="0 0 24 24"
      fill="currentColor"
      aria-hidden="true"
      focusable="false"
      className={`${className} ${tinta}`}
    >
      <path d={logo.path} />
    </svg>
  );
}
